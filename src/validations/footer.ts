import { z } from "zod";
import { safeUrlSchema } from "./siteSettings";

export const footerLinkItemSchema = z.object({
  id: z.string().trim().min(1),
  label: z.string().trim().min(1, "Display label is required").max(150),
  href: safeUrlSchema,
  isInternal: z.boolean().default(false),
  isDocument: z.boolean().default(false),
  mediaAssetId: z.string().nullable().optional(),
  enabled: z.boolean().default(true),
  sortOrder: z.number().int().default(0),
  target: z.enum(["_self", "_blank"]).default("_blank"),
  highlight: z.boolean().optional(),
});

export type FooterLinkItem = z.infer<typeof footerLinkItemSchema>;

export const footerColumnSchema = z.object({
  id: z.string().trim().min(1),
  title: z.string().trim().min(1, "Column title is required").max(100),
  sortOrder: z.number().int().default(0),
  links: z.array(footerLinkItemSchema).default([]),
});

export type FooterColumn = z.infer<typeof footerColumnSchema>;

export const footerBannerSchema = z.object({
  enabled: z.boolean().default(true),
  heading: z.string().trim().min(1, "Heading is required").max(150).default("Admissions Open"),
  description: z
    .string()
    .trim()
    .max(500)
    .default("Take your next step toward academic and professional excellence."),
  buttonLabel: z.string().trim().min(1, "Button label is required").max(80).default("Admission Open"),
  buttonUrl: safeUrlSchema.default("https://admissions.geetauniversity.edu.in/"),
});

export type FooterBanner = z.infer<typeof footerBannerSchema>;

export const footerBrandingSchema = z.object({
  logoUrl: safeUrlSchema.default("/GU-Logo.webp"),
  logoAlt: z.string().trim().max(150).default("Geeta University official logo"),
  description: z
    .string()
    .trim()
    .max(600)
    .default(
      "Step into the future with NextGen Smart Campus where innovation, technology, and world-class education come together to shape tomorrow’s leaders."
    ),
  applyNowLabel: z.string().trim().max(60).default("Apply Now →"),
  applyNowUrl: safeUrlSchema.default("https://admissions.geetauniversity.edu.in/"),
});

export type FooterBranding = z.infer<typeof footerBrandingSchema>;

export const footerLegalLinkSchema = z.object({
  id: z.string().trim().min(1),
  label: z.string().trim().min(1).max(100),
  href: safeUrlSchema,
  target: z.enum(["_self", "_blank"]).default("_blank"),
});

export type FooterLegalLink = z.infer<typeof footerLegalLinkSchema>;

export const footerLegalSchema = z.object({
  copyrightText: z.string().trim().max(200).default("Geeta University"),
  dynamicYear: z.boolean().default(true),
  links: z.array(footerLegalLinkSchema).default([
    {
      id: "privacy-policy",
      label: "Privacy Policy",
      href: "https://geetauniversity.edu.in/privacy-policy",
      target: "_blank",
    },
    {
      id: "terms-and-conditions",
      label: "Terms & Conditions",
      href: "https://geetauniversity.edu.in/terms-and-conditions",
      target: "_blank",
    },
    {
      id: "disclaimer",
      label: "Disclaimer",
      href: "https://geetauniversity.edu.in/disclaimer",
      target: "_blank",
    },
  ]),
});

export type FooterLegal = z.infer<typeof footerLegalSchema>;

export const footerSettingsSchema = z.object({
  banner: footerBannerSchema,
  branding: footerBrandingSchema,
  columns: z.array(footerColumnSchema).length(4, "Must have exactly 4 footer link columns"),
  legal: footerLegalSchema,
});

export type FooterSettings = z.infer<typeof footerSettingsSchema>;

